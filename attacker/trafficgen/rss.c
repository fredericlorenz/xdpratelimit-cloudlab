#include <ctype.h>
#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "trafficgen.h"

static int hex_value(char value) {
	if (value >= '0' && value <= '9')
		return value - '0';
	if (value >= 'a' && value <= 'f')
		return value - 'a' + 10;
	if (value >= 'A' && value <= 'F')
		return value - 'A' + 10;
	return -1;
}

static int parse_rss_key(const char *text, uint8_t *key) {
	size_t i = 0;
	for (;;) {
		int high;
		int low;

		while (*text == ':' || isspace((unsigned char)*text))
			text++;
		if (*text == '\0')
			break;
		if (i == RSS_KEY_LEN)
			return -1;
		high = hex_value(text[0]);
		low = text[0] != '\0' ? hex_value(text[1]) : -1;
		if (high < 0 || low < 0)
			return -1;
		key[i++] = (uint8_t)((high << 4) | low);
		text += 2;
	}
	return i >= 16 ? 0 : -1;
}

uint32_t rss_toeplitz_hash(uint32_t saddr_be, uint32_t daddr_be,
			   uint16_t sport_be, uint16_t dport_be,
			   const uint8_t *key) {
	uint8_t input[12];
	memcpy(input + 0, &saddr_be, 4);
	memcpy(input + 4, &daddr_be, 4);
	memcpy(input + 8, &sport_be, 2);
	memcpy(input + 10, &dport_be, 2);

	uint32_t hash = 0;
	uint32_t v = ((uint32_t)key[0] << 24) |
		     ((uint32_t)key[1] << 16) |
		     ((uint32_t)key[2] << 8)  |
		     ((uint32_t)key[3]);

	for (int i = 0; i < 12; i++) {
		for (int b = 7; b >= 0; b--) {
			if (input[i] & (1u << b))
				hash ^= v;
			v <<= 1;
			int bit_offset = (i * 8) + (7 - b) + 32;
			int byte_idx = bit_offset / 8;
			int bit_idx = 7 - (bit_offset % 8);
			if (key[byte_idx] & (1u << bit_idx))
				v |= 1u;
		}
	}
	return hash;
}

uint32_t rss_predict_queue(const struct rss_config *rss,
			   uint32_t saddr_be, uint32_t daddr_be,
			   uint16_t sport_be, uint16_t dport_be) {
	if (!rss->loaded || rss->indir_len == 0)
		return TG_QUEUE_UNKNOWN;
	uint32_t h = rss_toeplitz_hash(saddr_be, daddr_be, sport_be, dport_be, rss->key);
	return rss->indir[h % rss->indir_len];
}

int rss_has_queue(const struct rss_config *rss, uint32_t queue) {
	if (!rss->loaded)
		return 0;
	for (size_t i = 0; i < rss->indir_len; i++) {
		if (rss->indir[i] == queue)
			return 1;
	}
	return 0;
}

// Loads key=... and indir=... generated by extract_rss.py
int rss_load_file(const char *path, struct rss_config *rss) {
	FILE *f = fopen(path, "r");
	if (!f) {
		perror("fopen rss file");
		return -1;
	}

	memset(rss, 0, sizeof(*rss));
	char *line = NULL;
	size_t line_size = 0;
	int got_key = 0, got_indir = 0;

	while (getline(&line, &line_size, f) >= 0) {
		if (strncmp(line, "key=", 4) == 0) {
			if (parse_rss_key(line + 4, rss->key) != 0) {
				fprintf(stderr, "Invalid RSS key in %s\n", path);
				free(line);
				fclose(f);
				return -1;
			}
			got_key = 1;
		} else if (strncmp(line, "indir=", 6) == 0) {
			char *tok = strtok(line + 6, ", \t\r\n");
			while (tok) {
				char *end = NULL;
				unsigned long queue;

				if (rss->indir_len == RSS_INDIR_MAX) {
					fprintf(stderr, "RSS indirection table exceeds %u entries\n",
						RSS_INDIR_MAX);
					free(line);
					fclose(f);
					return -1;
				}
				errno = 0;
				queue = strtoul(tok, &end, 10);
				if (errno || !end || *end != '\0' || queue > UINT32_MAX) {
					fprintf(stderr, "Invalid RSS queue value: %s\n", tok);
					free(line);
					fclose(f);
					return -1;
				}
				rss->indir[rss->indir_len++] = (uint32_t)queue;
				tok = strtok(NULL, ", \t\r\n");
			}
			got_indir = (rss->indir_len > 0);
		}
	}

	int read_error = ferror(f);
	free(line);
	fclose(f);
	if (read_error) {
		fprintf(stderr, "Could not read RSS file %s\n", path);
		return -1;
	}
	if (!got_key || !got_indir) {
		fprintf(stderr, "Invalid RSS file %s (missing key= or indir=)\n", path);
		return -1;
	}
	if ((rss->indir_len & (rss->indir_len - 1)) != 0) {
		fprintf(stderr, "RSS indirection table length must be a power of two\n");
		return -1;
	}
	rss->loaded = 1;
	return 0;
}
